"""Export the evaluation results as LaTeX tables and a Markdown summary.

Produces two tables from the same run: ``results.tex`` (warm-start ranking
quality) and ``cold-start.tex`` (the slice that actually motivates this
project -- hybrid vs. ID-only MF vs. popularity on users/items withheld
entirely from training). Generating both from one script run is what stops
the paper's numbers from drifting away from what the code actually produces.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from recommender.cli import BEST_HYBRID, _build_models, _load  # noqa: E402
from recommender.evaluation import evaluate, evaluate_cold_start  # noqa: E402
from recommender.models import HybridWARPRecommender  # noqa: E402

WARM_COLUMNS = ["model", "ndcg", "recall", "map", "hit_rate", "coverage"]
COLD_COLUMNS = ["model", "slice", "ndcg", "recall", "map", "hit_rate"]
HEADERS = {
    "model": "Model",
    "slice": "Slice",
    "ndcg": "NDCG@10",
    "recall": "Recall@10",
    "map": "MAP@10",
    "hit_rate": "Hit rate",
    "coverage": "Coverage",
}


def compute_results(
    reviews: Path, products: Path, k: int, seed: int
) -> tuple[pd.DataFrame, pd.DataFrame]:
    _, split, feature_store = _load(reviews, products, seed)

    warm_rows, cold_rows = [], []
    for name, model in _build_models(seed).items():
        model.fit(split)
        warm_rows.append(evaluate(model, split, k=k, partition="test", model_name=name).as_row())
        for report in evaluate_cold_start(model, split, k=k, model_name=name).values():
            cold_rows.append(report.as_row())

    hybrid = HybridWARPRecommender(random_state=seed, **BEST_HYBRID)
    hybrid.fit(split, feature_store.user_matrix, feature_store.item_matrix)
    hybrid_report = evaluate(hybrid, split, k=k, partition="test", model_name="Hybrid WARP")
    warm_rows.append(hybrid_report.as_row())
    for report in evaluate_cold_start(hybrid, split, k=k, model_name="Hybrid WARP").values():
        cold_rows.append(report.as_row())

    warm = pd.DataFrame(warm_rows)[WARM_COLUMNS].sort_values("ndcg", ascending=False)
    cold = pd.DataFrame(cold_rows)[COLD_COLUMNS].sort_values(
        ["slice", "ndcg"], ascending=[True, False]
    )
    return warm, cold


def to_latex_warm(frame: pd.DataFrame, k: int) -> str:
    best = frame["ndcg"].max()
    lines = [
        "% Generated by scripts/export_results_table.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        rf"  \caption{{Warm-start ranking quality on the held-out test partition ($K={k}$).",
        r"  Hyperparameters were fixed before the test partition was read once.}",
        r"  \label{tab:results}",
        r"  \begin{tabular}{lrrrrr}",
        r"    \toprule",
        "    " + " & ".join(HEADERS[c] for c in WARM_COLUMNS) + r" \\",
        r"    \midrule",
    ]
    for _, row in frame.iterrows():
        cells = [str(row["model"]).replace("_", r"\_")]
        for col in WARM_COLUMNS[1:]:
            value = f"{row[col]:.4f}"
            cells.append(rf"\textbf{{{value}}}" if col == "ndcg" and row[col] == best else value)
        lines.append("    " + " & ".join(cells) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def to_latex_cold(frame: pd.DataFrame, k: int) -> str:
    slice_labels = {
        "cold_user": "New user, known item",
        "cold_item": "Known user, new item",
        "cold_both": "New user, new item",
    }
    lines = [
        "% Generated by scripts/export_results_table.py -- do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        rf"  \caption{{Cold-start retrieval quality ($K={k}$). Users/items in this",
        r"  slice were withheld from training entirely; the ID-only baseline and the",
        r"  popularity baseline can only fall back to a popularity prior for them,",
        r"  while the hybrid model scores them through shared category, brand and",
        r"  ingredient features.}",
        r"  \label{tab:cold-start}",
        r"  \begin{tabular}{llrrrr}",
        r"    \toprule",
        "    " + " & ".join(HEADERS[c] for c in COLD_COLUMNS) + r" \\",
        r"    \midrule",
    ]
    for _, row in frame.iterrows():
        cells = [
            str(row["model"]).replace("_", r"\_"),
            slice_labels.get(str(row["slice"]), str(row["slice"])),
        ]
        cells += [f"{row[col]:.4f}" for col in COLD_COLUMNS[2:]]
        lines.append("    " + " & ".join(cells) + r" \\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    return "\n".join(lines)


def to_markdown(frame: pd.DataFrame, columns: list[str]) -> str:
    header = "| " + " | ".join(HEADERS[c] for c in columns) + " |"
    sep = "|" + "|".join(["---"] * len(columns)) + "|"
    rows = []
    for _, r in frame.iterrows():
        cells = [str(r[columns[0]])]
        if "slice" in columns:
            cells.append(str(r["slice"]))
            numeric_cols = columns[2:]
        else:
            numeric_cols = columns[1:]
        cells += [f"{r[c]:.4f}" for c in numeric_cols]
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join([header, sep, *rows])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reviews", type=Path, default=PROJECT_ROOT / "data" / "reviews.csv")
    parser.add_argument(
        "--products", type=Path, default=PROJECT_ROOT / "data" / "product_info.csv"
    )
    parser.add_argument("--k", type=int, default=10)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    if not args.reviews.exists():
        raise SystemExit(f"{args.reviews} not found. Run scripts/download_data.py --synthetic")

    warm, cold = compute_results(args.reviews, args.products, args.k, args.seed)

    tables = PROJECT_ROOT / "paper" / "tables"
    tables.mkdir(parents=True, exist_ok=True)
    (tables / "results.tex").write_text(to_latex_warm(warm, args.k))
    (tables / "cold-start.tex").write_text(to_latex_cold(cold, args.k))

    artifacts = PROJECT_ROOT / "artifacts"
    artifacts.mkdir(exist_ok=True)
    warm.to_csv(artifacts / "results_warm.csv", index=False)
    cold.to_csv(artifacts / "results_cold_start.csv", index=False)
    (artifacts / "results.md").write_text(
        to_markdown(warm, WARM_COLUMNS) + "\n\n" + to_markdown(cold, COLD_COLUMNS) + "\n"
    )

    print(to_markdown(warm, WARM_COLUMNS))
    print()
    print(to_markdown(cold, COLD_COLUMNS))
    print(f"\nwrote {tables / 'results.tex'}, {tables / 'cold-start.tex'}")
    print(f"wrote {artifacts / 'results.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
